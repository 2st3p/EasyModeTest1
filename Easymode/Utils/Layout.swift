import SwiftUI

/// Standard layout constants for consistent spacing
enum Layout {
    /// Standard top padding for page headers (below safe area)
    static let headerTop: CGFloat = 48

    /// Standard horizontal padding for page content
    static let horizontalPadding: CGFloat = 24

    /// Standard bottom padding for content above tab bar
    static let tabBarPadding: CGFloat = 80
}
